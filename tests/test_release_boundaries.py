def test_decrypted_invalid_utf8_is_a_controlled_payment_error():
    import base64

    from cryptography.hazmat.primitives.ciphers.aead import AESGCM

    from app.wechat_pay import decrypt_resource
    from tests.test_wechat_notify import AES_NONCE, API_V3_KEY

    raw = AESGCM(API_V3_KEY.encode()).encrypt(AES_NONCE.encode(), b'\xff', b'')
    with pytest.raises(WeChatPayError):
        decrypt_resource(API_V3_KEY, nonce=AES_NONCE, ciphertext=base64.b64encode(raw).decode())


