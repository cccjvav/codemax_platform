@pytest.mark.parametrize('kind', ['admin', 'client', 'missing_admin', 'checksum', 'pending', 'renamed_admin'])
async def test_production_rejects_demo_rehashed_secrets_and_bad_ledger(safe_database, kind):
    async with TestSession() as db:
        if kind in ('admin', 'renamed_admin'):
            db.add(User(username='admin' if kind == 'admin' else 'renamed', password=hash_password('123456'), role=1))
        elif kind == 'client':
            client = await db.scalar(select(OAuthClient).where(OAuthClient.client_id == 'tools'))
            client.status = 1  # hash was freshly generated by fixture, not the static seed hash
        elif kind == 'missing_admin':
            owner = await db.scalar(select(User).where(User.username == 'owner'))
            owner.role = 0
        elif kind == 'pending':
            await db.delete(await db.get(SchemaMigration, '0009'))
        else:
            (await db.get(SchemaMigration, '0001')).checksum = 'bad'
        await db.commit()
    with pytest.raises(ProductionConfigError):
        await enforce_database_safety(TestSession)


async def test_production_oauth_requires_explicit_first_party_allowlist(client, monkeypatch):
    headers = await auth_headers(client)
    monkeypatch.setattr(settings, 'ENV', 'production')
    monkeypatch.setattr(settings, 'OAUTH_TRUSTED_CLIENT_IDS', ())
    params = {'client_id': 'tools', 'redirect_uri': 'https://tools.codemax.top/callback', 'response_type': 'code'}
    assert (await client.get('/oauth/authorize', params=params, headers=headers)).status_code == 400
    data = {'grant_type': 'authorization_code', 'client_id': 'tools', 'client_secret': 'codemax-tools-secret',
            'code': 'absent', 'redirect_uri': params['redirect_uri']}
    assert (await client.post('/oauth/token', data=data)).json()['detail']['error'] == 'invalid_client'
    monkeypatch.setattr(settings, 'OAUTH_TRUSTED_CLIENT_IDS', ('tools',))
    assert (await client.get('/oauth/authorize', params=params, headers=headers)).status_code == 200


